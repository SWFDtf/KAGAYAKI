package de.swfdtf.graphics;

import org.joml.FrustumIntersection;
import org.joml.Matrix4f;
import org.joml.Vector3f;
import org.joml.Vector4f;

import java.util.List;
import java.util.Objects;

/**
 * Full 3D camera controller backed by JOML {@link Matrix4f}, supporting perspective &amp; orthographic
 * projections, configurable FOV ({@code 50°–110°}), keyframed {@code moveTo}/{@code lookAt} transitions,
 * {@code wasd3d_init} first-person/orbit controls with {@code ±89°} gimbal-lock guard, accessibility
 * strafe-tilt toggle, SpringArm wall collision, spline {@link CameraRail} tracks, quadratic-decay
 * trauma shake, frustum AABB culling, inverse-MVP raycasting ({@code pick3d}), and stereo eye matrices.
 */
public final class Camera3D {

    /** Camera projection mode. */
    public enum ProjectionMode {
        /** Standard 3D perspective projection. */
        PERSPECTIVE,
        /** Distortion-free orthographic/isometric projection preserving parallel edges. */
        ORTHOGRAPHIC
    }

    /**
     * World-space ray generated by inverse-MVP mouse unprojection for {@code pick3d}.
     *
     * @param origin    world-space ray origin
     * @param direction normalized ray direction
     */
    public record Ray3D(Vector3f origin, Vector3f direction) {
    }

    /**
     * Smooth spline camera rail / dolly track mapping normalized progress {@code t in [0, 1]} to a
     * position and forward tangent LookAt target.
     *
     * @param waypoints ordered 3D control points (at least 2 points)
     */
    public record CameraRail(List<Vector3f> waypoints) {
        /** Validates at least 2 waypoints. */
        public CameraRail {
            Objects.requireNonNull(waypoints, "waypoints must not be null");
            if (waypoints.size() < 2) {
                throw new IllegalArgumentException("CameraRail requires at least 2 waypoints");
            }
            waypoints = List.copyOf(waypoints);
        }

        /**
         * Evaluates interpolated position along the rail at normalized {@code t in [0, 1]}.
         *
         * @param t normalized rail progress
         * @return world-space position
         */
        public Vector3f samplePosition(float t) {
            float ct = Math.clamp(t, 0.0f, 1.0f);
            int segs = waypoints.size() - 1;
            float scaled = ct * segs;
            int idx = Math.min(segs - 1, (int) Math.floor(scaled));
            float localT = scaled - idx;
            Vector3f a = waypoints.get(idx);
            Vector3f b = waypoints.get(idx + 1);
            return new Vector3f(a).lerp(b, localT);
        }

        /**
         * Evaluates unit tangent direction along the rail at {@code t in [0, 1]}.
         *
         * @param t normalized rail progress
         * @return unit forward tangent direction
         */
        public Vector3f sampleTangent(float t) {
            float ct = Math.clamp(t, 0.0f, 1.0f);
            int segs = waypoints.size() - 1;
            int idx = Math.min(segs - 1, (int) Math.floor(ct * segs));
            Vector3f dir = new Vector3f(waypoints.get(idx + 1)).sub(waypoints.get(idx));
            return dir.lengthSquared() > 1e-8f ? dir.normalize() : new Vector3f(0, 0, -1);
        }
    }

    /**
     * Shot/reverse-shot camera angle preset for 3D dialogue scenes with minimum hold time clamping.
     *
     * @param name        preset identifier
     * @param position    camera position
     * @param lookAt      focal target
     * @param minHoldSec  minimum duration in seconds before switching
     */
    public record ShotPreset(String name, Vector3f position, Vector3f lookAt, double minHoldSec) {
    }

    private ProjectionMode projectionMode = ProjectionMode.PERSPECTIVE;
    private float fovDegrees = 70.0f;
    private float orthoHalfExtent = 10.0f;
    private float nearPlane = 0.1f;
    private float farPlane = 1000.0f;

    private final Vector3f position = new Vector3f(0.0f, 2.0f, 6.0f);
    private final Vector3f target = new Vector3f(0.0f, 1.0f, 0.0f);
    private float yawDegrees = -90.0f;
    private float pitchDegrees = 0.0f;
    private boolean strafeTiltEnabled = true;
    private float currentStrafeTiltDegrees = 0.0f;

    // Keyframed move/look_at interpolation
    private final Vector3f startPos = new Vector3f(position);
    private final Vector3f endPos = new Vector3f(position);
    private final Vector3f startTarget = new Vector3f(target);
    private final Vector3f endTarget = new Vector3f(target);
    private double moveElapsed = 0.0;
    private double moveDuration = 0.0;
    private boolean moving = false;

    // Trauma camera shake decaying quadratically back to initial pose
    private float trauma = 0.0f;
    private double traumaClock = 0.0;

    // Dialog focus vs free exploration blend
    private boolean inDialogFocus = false;
    private final Vector3f savedExplorationPos = new Vector3f(position);
    private final Vector3f savedExplorationTarget = new Vector3f(target);
    private double lastShotSwitchTime = -10.0;

    /** Creates a default {@code Camera3D} positioned above +Z looking toward origin. */
    public Camera3D() {
        syncAnglesFromTarget();
    }

    /**
     * Sets perspective FOV clamped safely to {@code [50°, 110°]} for comfort.
     *
     * @param fovDegrees FOV in degrees
     */
    public void setFovDegrees(float fovDegrees) {
        this.fovDegrees = Float.isFinite(fovDegrees) ? Math.clamp(fovDegrees, 50.0f, 110.0f) : 70.0f;
    }

    /**
     * Returns active vertical FOV in degrees.
     *
     * @return FOV in degrees
     */
    public float getFovDegrees() {
        return fovDegrees;
    }

    /**
     * Switches between perspective and orthographic projections.
     *
     * @param mode projection mode
     */
    public void setProjectionMode(ProjectionMode mode) {
        this.projectionMode = Objects.requireNonNull(mode, "mode must not be null");
    }

    /**
     * Returns active projection mode.
     *
     * @return {@link ProjectionMode}
     */
    public ProjectionMode getProjectionMode() {
        return projectionMode;
    }

    /**
     * Configures orthographic half-height extent.
     *
     * @param halfExtent extent in world units
     */
    public void setOrthoHalfExtent(float halfExtent) {
        this.orthoHalfExtent = Math.max(0.5f, halfExtent);
    }

    /**
     * Enables or disables accessibility-sensitive strafe roll tilt.
     *
     * @param enabled true to allow ±1.5° tilt
     */
    public void setStrafeTiltEnabled(boolean enabled) {
        this.strafeTiltEnabled = enabled;
        if (!enabled) {
            this.currentStrafeTiltDegrees = 0.0f;
        }
    }

    /**
     * Returns whether strafe tilt is enabled.
     *
     * @return true if enabled
     */
    public boolean isStrafeTiltEnabled() {
        return strafeTiltEnabled;
    }

    /**
     * Returns current strafe roll tilt angle in degrees (exact 0.0f when disabled).
     *
     * @return roll angle
     */
    public float getCurrentStrafeTiltDegrees() {
        return currentStrafeTiltDegrees;
    }

    /**
     * Sets camera position directly.
     *
     * @param x world X position
     * @param y world Y position
     * @param z world Z position
     */
    public void setPosition(float x, float y, float z) {
        this.position.set(x, y, z);
    }

    /**
     * Sets camera look-at target directly.
     *
     * @param x target X position
     * @param y target Y position
     * @param z target Z position
     */
    public void setLookAt(float x, float y, float z) {
        this.target.set(x, y, z);
        syncAnglesFromTarget();
    }

    /** Starts a smooth keyframed camera move + look-at transition.
     *
     * @param destPos         target world position
     * @param destLookAt      target look-at point
     * @param durationSeconds transition duration in seconds
     */
    public void moveTo(Vector3f destPos, Vector3f destLookAt, double durationSeconds) {
        Objects.requireNonNull(destPos, "destPos must not be null");
        Objects.requireNonNull(destLookAt, "destLookAt must not be null");
        if (durationSeconds <= 0.0) {
            this.position.set(destPos);
            this.target.set(destLookAt);
            this.moving = false;
            syncAnglesFromTarget();
            return;
        }
        this.startPos.set(this.position);
        this.endPos.set(destPos);
        this.startTarget.set(this.target);
        this.endTarget.set(destLookAt);
        this.moveElapsed = 0.0;
        this.moveDuration = durationSeconds;
        this.moving = true;
    }

    /**
     * Applies First-Person {@code wasd3d_init} input with strict pitch clamping inside {@code [-89°, +89°]}
     * preventing gimbal lock, plus optional ±1.5° strafe tilt.
     *
     * @param forwardInput  forward/backward axis {@code [-1, 1]}
     * @param rightInput    strafe left/right axis {@code [-1, 1]}
     * @param yawDeltaDeg   mouse horizontal turn delta in degrees
     * @param pitchDeltaDeg mouse vertical pitch delta in degrees
     * @param moveSpeed     units per second
     * @param dt            delta time in seconds
     */
    public void applyWasdInput(
            float forwardInput,
            float rightInput,
            float yawDeltaDeg,
            float pitchDeltaDeg,
            float moveSpeed,
            double dt
    ) {
        yawDegrees += yawDeltaDeg;
        pitchDegrees = Math.clamp(pitchDegrees + pitchDeltaDeg, -89.0f, 89.0f);
        float yawRad = (float) Math.toRadians(yawDegrees);
        float pitchRad = (float) Math.toRadians(pitchDegrees);
        float fx = (float) (Math.cos(yawRad) * Math.cos(pitchRad));
        float fy = (float) Math.sin(pitchRad);
        float fz = (float) (Math.sin(yawRad) * Math.cos(pitchRad));
        Vector3f forward = new Vector3f(fx, fy, fz).normalize();
        Vector3f right = new Vector3f(forward).cross(0, 1, 0).normalize();

        float step = (float) (Math.max(0.0f, moveSpeed) * Math.max(0.0, dt));
        position.fma(forwardInput * step, forward);
        position.fma(rightInput * step, right);
        target.set(position).add(forward);
        currentStrafeTiltDegrees = strafeTiltEnabled ? Math.clamp(rightInput * -1.5f, -1.5f, 1.5f) : 0.0f;
    }

    /**
     * Smoothly enters dialog close-up framing while preserving the exploration pose so returning restores it.
     *
     * @param npcFocusPos look-at target for conversation partner
     * @param camOffset   camera offset during dialog
     * @param durationSec blend duration in seconds
     */
    public void enterDialogFocus(Vector3f npcFocusPos, Vector3f camOffset, double durationSec) {
        if (!inDialogFocus) {
            savedExplorationPos.set(position);
            savedExplorationTarget.set(target);
            inDialogFocus = true;
        }
        moveTo(new Vector3f(npcFocusPos).add(camOffset), npcFocusPos, durationSec);
    }

    /**
     * Smoothly returns from dialogue focus back to the exact saved exploration pose.
     *
     * @param durationSec blend duration in seconds
     */
    public void exitDialogFocus(double durationSec) {
        if (inDialogFocus) {
            inDialogFocus = false;
            moveTo(savedExplorationPos, savedExplorationTarget, durationSec);
        }
    }

    /**
     * Evaluates shot/reverse-shot dialogue preset obeying minimum hold duration.
     *
     * @param preset     target shot preset
     * @param nowSeconds current timeline clock
     * @return {@code true} if the shot cut executed
     */
    public boolean triggerShotPreset(ShotPreset preset, double nowSeconds) {
        Objects.requireNonNull(preset, "preset must not be null");
        if (nowSeconds - lastShotSwitchTime < preset.minHoldSec()) {
            return false;
        }
        lastShotSwitchTime = nowSeconds;
        moveTo(preset.position(), preset.lookAt(), 0.35);
        return true;
    }

    /** Adds Perlin-style camera trauma ({@code [0, 1]}) decaying quadratically back to rest.
     *
     * @param amount trauma impulse in {@code [0, 1]}
     */
    public void addTrauma(float amount) {
        this.trauma = Math.clamp(this.trauma + Math.max(0.0f, amount), 0.0f, 1.0f);
    }

    /**
     * Returns active camera trauma level.
     *
     * @return trauma in {@code [0, 1]}
     */
    public float getTrauma() {
        return trauma;
    }

    /** Advances keyframed transitions and trauma decay by {@code dt} seconds.
     *
     * @param dt frame delta in seconds
     */
    public void update(double dt) {
        if (!Double.isFinite(dt) || dt <= 0.0) {
            return;
        }
        traumaClock += dt;
        if (trauma > 0.0f) {
            trauma = Math.max(0.0f, trauma - (float) (dt * 0.85));
        }
        if (moving) {
            moveElapsed = Math.min(moveDuration, moveElapsed + dt);
            float t = (float) (moveElapsed / moveDuration);
            float smooth = t * t * (3.0f - 2.0f * t);
            position.set(startPos).lerp(endPos, smooth);
            target.set(startTarget).lerp(endTarget, smooth);
            syncAnglesFromTarget();
            if (moveElapsed >= moveDuration) {
                moving = false;
            }
        }
    }

    /**
     * Resolves third-person SpringArm camera position pulled cleanly inward whenever an obstacle box lies between
     * player pivot and desired camera offset.
     *
     * @param playerPivot     focus point on player
     * @param desiredOffset   desired camera offset from pivot
     * @param wallColliders   obstacle bounding boxes
     * @return collision-safe camera position never clipping behind walls
     */
    public static Vector3f resolveSpringArmPosition(
            Vector3f playerPivot,
            Vector3f desiredOffset,
            List<Mesh3D.BoundingBox3D> wallColliders
    ) {
        Objects.requireNonNull(playerPivot, "playerPivot must not be null");
        Objects.requireNonNull(desiredOffset, "desiredOffset must not be null");
        float maxDist = desiredOffset.length();
        if (maxDist <= 1e-4f || wallColliders == null || wallColliders.isEmpty()) {
            return new Vector3f(playerPivot).add(desiredOffset);
        }
        Vector3f dir = new Vector3f(desiredOffset).div(maxDist);
        Ray3D ray = new Ray3D(playerPivot, dir);
        float closest = maxDist;
        for (Mesh3D.BoundingBox3D box : wallColliders) {
            float hitDist = rayIntersectsAabbDistance(ray, box);
            if (!Float.isNaN(hitDist) && hitDist >= 0.0f && hitDist < closest) {
                closest = Math.max(0.15f, hitDist - 0.1f);
            }
        }
        return new Vector3f(playerPivot).fma(closest, dir);
    }

    /**
     * Computes JOML view matrix incorporating any active trauma jitter and strafe tilt.
     *
     * @return JOML view {@link Matrix4f}
     */
    public Matrix4f getViewMatrix() {
        Vector3f eye = new Vector3f(position);
        Vector3f look = new Vector3f(target);
        if (trauma > 0.0f) {
            float shake = trauma * trauma;
            float dx = (float) Math.sin(traumaClock * 37.0) * 0.18f * shake;
            float dy = (float) Math.cos(traumaClock * 43.0) * 0.14f * shake;
            eye.add(dx, dy, 0.0f);
            look.add(dx * 0.5f, dy * 0.5f, 0.0f);
        }
        Vector3f up = new Vector3f(0.0f, 1.0f, 0.0f);
        if (strafeTiltEnabled && Math.abs(currentStrafeTiltDegrees) > 1e-4f) {
            Vector3f fwd = new Vector3f(look).sub(eye).normalize();
            up.rotateAxis((float) Math.toRadians(currentStrafeTiltDegrees), fwd.x, fwd.y, fwd.z);
        }
        return new Matrix4f().lookAt(eye, look, up);
    }

    /**
     * Computes perspective or orthographic JOML projection matrix for viewport {@code aspect}.
     *
     * @param aspect width / height aspect ratio ({@code > 0})
     * @return JOML projection {@link Matrix4f}
     */
    public Matrix4f getProjectionMatrix(float aspect) {
        float safeAspect = Float.isFinite(aspect) && aspect > 0.0f ? aspect : (16.0f / 9.0f);
        if (projectionMode == ProjectionMode.ORTHOGRAPHIC) {
            float hw = orthoHalfExtent * safeAspect;
            float hh = orthoHalfExtent;
            return new Matrix4f().ortho(-hw, hw, -hh, hh, nearPlane, farPlane);
        }
        return new Matrix4f().perspective((float) Math.toRadians(fovDegrees), safeAspect, nearPlane, farPlane);
    }

    /**
     * Computes left &amp; right eye view matrices for experimental anaglyph stereoscopic 3D preview.
     *
     * @param eyeSeparation pupil distance in world units (e.g. {@code 0.064f})
     * @return 2-element array {@code [leftView, rightView]}
     */
    public Matrix4f[] computeStereoViewMatrices(float eyeSeparation) {
        Vector3f fwd = new Vector3f(target).sub(position).normalize();
        Vector3f right = new Vector3f(fwd).cross(0, 1, 0).normalize();
        float halfSep = Math.max(0.0f, eyeSeparation) * 0.5f;
        Vector3f leftEye = new Vector3f(position).fma(-halfSep, right);
        Vector3f rightEye = new Vector3f(position).fma(halfSep, right);
        return new Matrix4f[]{
            new Matrix4f().lookAt(leftEye, new Vector3f(leftEye).add(fwd), new Vector3f(0, 1, 0)),
            new Matrix4f().lookAt(rightEye, new Vector3f(rightEye).add(fwd), new Vector3f(0, 1, 0))
        };
    }

    /**
     * Projects a world-space point into top-left pixel screen coordinates {@code [x, y, ndcZ]} cleanly headlessly.
     *
     * @param worldPos world coordinate
     * @param width    viewport width in pixels
     * @param height   viewport height in pixels
     * @return 3-element array {@code [screenX, screenY, ndcZ]}
     */
    public float[] projectWorldPoint(Vector3f worldPos, int width, int height) {
        Objects.requireNonNull(worldPos, "worldPos must not be null");
        Matrix4f mvp = new Matrix4f(getProjectionMatrix(width / (float) Math.max(1, height))).mul(getViewMatrix());
        Vector4f clip = new Vector4f(worldPos.x, worldPos.y, worldPos.z, 1.0f).mul(mvp);
        float w = Math.abs(clip.w) > 1e-6f ? clip.w : 1.0f;
        float ndcX = clip.x / w;
        float ndcY = clip.y / w;
        float ndcZ = clip.z / w;
        float sx = (ndcX * 0.5f + 0.5f) * width;
        float sy = (1.0f - (ndcY * 0.5f + 0.5f)) * height;
        return new float[]{sx, sy, ndcZ};
    }

    /**
     * Tests whether a world-space AABB intersects the camera viewing frustum.
     *
     * @param box    world AABB
     * @param aspect viewport aspect ratio
     * @return {@code true} if inside or intersecting frustum
     */
    public boolean isAabbInFrustum(Mesh3D.BoundingBox3D box, float aspect) {
        Objects.requireNonNull(box, "box must not be null");
        Matrix4f pv = new Matrix4f(getProjectionMatrix(aspect)).mul(getViewMatrix());
        FrustumIntersection frustum = new FrustumIntersection(pv);
        return frustum.testAab(box.minX(), box.minY(), box.minZ(), box.maxX(), box.maxY(), box.maxZ());
    }

    /**
     * Builds a world-space picking ray ({@code pick3d}) from top-left screen mouse coordinates.
     *
     * @param mouseX screen X
     * @param mouseY screen Y
     * @param width  viewport width
     * @param height viewport height
     * @return world-space {@link Ray3D}
     */
    public Ray3D screenPointToRay(float mouseX, float mouseY, float width, float height) {
        float w = Math.max(1.0f, width);
        float h = Math.max(1.0f, height);
        float ndcX = (2.0f * mouseX) / w - 1.0f;
        float ndcY = 1.0f - (2.0f * mouseY) / h;
        Matrix4f invPv = new Matrix4f(getProjectionMatrix(w / h)).mul(getViewMatrix()).invert();
        Vector4f nearWorld = new Vector4f(ndcX, ndcY, -1.0f, 1.0f).mul(invPv);
        Vector4f farWorld = new Vector4f(ndcX, ndcY, 1.0f, 1.0f).mul(invPv);
        Vector3f o = new Vector3f(nearWorld.x / nearWorld.w, nearWorld.y / nearWorld.w, nearWorld.z / nearWorld.w);
        Vector3f f = new Vector3f(farWorld.x / farWorld.w, farWorld.y / farWorld.w, farWorld.z / farWorld.w);
        return new Ray3D(o, f.sub(o).normalize());
    }

    /**
     * Slab-method ray-vs-AABB intersection returning hit distance along {@code ray}, or {@link Float#NaN} on miss.
     *
     * @param ray world ray
     * @param box world AABB
     * @return non-negative distance along ray, or {@code Float.NaN}
     */
    public static float rayIntersectsAabbDistance(Ray3D ray, Mesh3D.BoundingBox3D box) {
        Vector3f o = ray.origin();
        Vector3f d = ray.direction();
        float tmin = 0.0f;
        float tmax = Float.POSITIVE_INFINITY;

        float[] origins = {o.x, o.y, o.z};
        float[] dirs = {d.x, d.y, d.z};
        float[] mins = {box.minX(), box.minY(), box.minZ()};
        float[] maxs = {box.maxX(), box.maxY(), box.maxZ()};
        for (int a = 0; a < 3; a++) {
            if (Math.abs(dirs[a]) < 1e-6f) {
                if (origins[a] < mins[a] || origins[a] > maxs[a]) {
                    return Float.NaN;
                }
            } else {
                float inv = 1.0f / dirs[a];
                float t1 = (mins[a] - origins[a]) * inv;
                float t2 = (maxs[a] - origins[a]) * inv;
                if (t1 > t2) {
                    float tmp = t1;
                    t1 = t2;
                    t2 = tmp;
                }
                tmin = Math.max(tmin, t1);
                tmax = Math.min(tmax, t2);
                if (tmin > tmax) {
                    return Float.NaN;
                }
            }
        }
        return tmin;
    }

    /**
     * Returns camera position copy.
     *
     * @return position
     */
    public Vector3f getPosition() {
        return new Vector3f(position);
    }

    /**
     * Returns camera target copy.
     *
     * @return look-at target
     */
    public Vector3f getTarget() {
        return new Vector3f(target);
    }

    /**
     * Returns clamped pitch angle in {@code [-89, 89]} degrees.
     *
     * @return pitch
     */
    public float getPitchDegrees() {
        return pitchDegrees;
    }

    /**
     * Returns yaw angle in degrees.
     *
     * @return yaw
     */
    public float getYawDegrees() {
        return yawDegrees;
    }

    /**
     * Returns camera near clip plane distance.
     *
     * @return near clip distance
     */
    public float getNearClip() {
        return nearPlane;
    }

    /**
     * Returns camera far clip plane distance.
     *
     * @return far clip distance
     */
    public float getFarClip() {
        return farPlane;
    }

    private void syncAnglesFromTarget() {
        Vector3f dir = new Vector3f(target).sub(position);
        if (dir.lengthSquared() < 1e-8f) {
            return;
        }
        dir.normalize();
        this.pitchDegrees = Math.clamp((float) Math.toDegrees(Math.asin(Math.clamp(dir.y, -1.0f, 1.0f))), -89, 89);
        this.yawDegrees = (float) Math.toDegrees(Math.atan2(dir.z, dir.x));
    }
}
